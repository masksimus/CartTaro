import { readdir, readFile, writeFile, cp, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root=new URL('../v6/',import.meta.url);
const demoHTML=(await readFile(new URL('index.html',root),'utf8')).replace('<head>','<head>\n  <meta name="arcana-demo-only" content="true">');
await writeFile(new URL('demo.html',root),demoHTML);
const files=['index.html','demo.html','style.css','startup.js','app.js','game.mjs','content.mjs','LICENSES.txt','assets/back.svg','assets/grain.svg','assets/serif.woff','assets/sans.woff','assets/FONT-LICENSE.txt','assets/seal.svg',...['today','readings','collection','quests','profile'].map(x=>'assets/nav-'+x+'.svg'),'vendor/vk-bridge-2.14.0.min.js','vendor/VK-BRIDGE-LICENSE.txt',...(await readdir(new URL('assets/cards/',root))).sort().map(x=>'assets/cards/'+x)];
const vendor=await readFile(new URL('../node_modules/@vkontakte/vk-bridge/dist/browser.min.js',import.meta.url));
if(!vendor.equals(await readFile(new URL('vendor/vk-bridge-2.14.0.min.js',root))))throw Error('Vendored Bridge differs from pinned package');
const hash=createHash('sha256');for(const file of files)hash.update(file).update(await readFile(new URL(file,root)));
const version=hash.digest('hex').slice(0,16);
const worker=`// Generated by scripts/v6-build.mjs. Cache only this explicit public static allowlist.
const CACHE='arcana-v6-${version}';
const FILES=${JSON.stringify(files.map(x=>'./'+x))};
const urls=FILES.map(x=>new URL(x,self.registration.scope).href);
// A cached redirected response cannot satisfy a later manual-mode navigation.
// Store the public bytes as a fresh response, including during precache.
const cacheable=async response=>new Response(await response.arrayBuffer(),{status:response.status,statusText:response.statusText,headers:response.headers});
self.addEventListener('install',event=>event.waitUntil(caches.open(CACHE).then(cache=>Promise.all(urls.map(async url=>{
  const response=await fetch(url,{credentials:'omit'});
  if(!response.ok)throw Error('offline_asset_unavailable');
  await cache.put(url,await cacheable(response));
})))));
self.addEventListener('activate',event=>event.waitUntil(caches.keys().then(keys=>Promise.all(keys.filter(k=>k.startsWith('arcana-v6-')&&k!==CACHE).map(k=>caches.delete(k)))).then(()=>self.clients.claim())));
self.addEventListener('fetch',event=>{
  const request=event.request,url=new URL(request.url);
  // Static hosts may canonicalize index.html to /. Cache and restore both.
  const key=url.href===self.registration.scope?new URL('index.html',self.registration.scope).href:url.href;
  // Never intercept signed navigation, APIs, credentials or foreign origins.
  if(request.method!=='GET'||url.search||request.headers.has('authorization')||!urls.includes(key))return;
  event.respondWith(fetch(request).then(response=>{
    if(response.ok){const copy=response.clone();event.waitUntil(cacheable(copy).then(value=>caches.open(CACHE).then(cache=>cache.put(key,value))));}
    return response;
  }).catch(()=>caches.match(key).then(cached=>cached||Response.error())));
});
`;
await writeFile(new URL('sw.js',root),worker);
await mkdir(new URL('dist/',root),{recursive:true});
for(const f of [...files,'sw.js']){const target=new URL('dist/'+f,root);await mkdir(new URL('.',target),{recursive:true});await cp(new URL(f,root),target);}
const html=await readFile(new URL('dist/index.html',root),'utf8');
await writeFile(new URL('dist/index.html',root),html.replace('<head>','<head>\n  <meta name="arcana-demo-only" content="true">'));
console.log('V6 static-only build: '+files.length+' local assets, cache '+version);
