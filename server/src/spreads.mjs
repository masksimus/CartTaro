const ONE_POSITIONS = Object.freeze(['Главная тема']);
const THREE_POSITIONS = Object.freeze(['Что было', 'Что происходит', 'Куда направить внимание']);

/** A cryptographically random spread of 1 or 3 DISTINCT cards.
 * Reversed cards show a reflective shadow meaning, not bad luck.
 * No persistence or token/secret/user information in the response. */
export function createSpread(count, { integer = randomInt, now = () => Date.now() } = {}) {
  if (count !== 1 && count !== 3) throw new TypeError('Unsupported spread size');
  const bag = [...MAJOR_ARCANA.keys()];
  const cards = [];
  for (let i = 0; i < count; i++) {
    const selectedIndex = integer(bag.length);
    if (!Number.isInteger(selectedIndex) || selectedIndex < 0 || selectedIndex >= bag.length) {
      throw new Error('Invalid entropy source');
    }
    const id = bag.splice(selectedIndex,1)[0];
    const arcana = MAJOR_ARCANA[id];
    const reversed = integer(4) === 0;
    cards.push({
      id, name:arcana.name,title:arcana.title,sigil:arcana.sigil,
      position:(count === 1 ? ONE_POSITIONS : THREE_POSITIONS)[i],
      reversed,
      meaning:reversed ? arcana.shadow : arcana.light,
      advice:arcana.advice
    });
  }
  const summary = count === 1 ?
    'Взгляните на тему дня через эту карту. Решение остаётся за вами.' :
    'Сопоставьте прежний опыт, нынешнюю ситуацию и следующий осмысленный шаг.';
  return {
    kind:count === 1 ? 'one' : 'three',
    cards,summary,generatedAt:new Date(now()).toISOString(),
    note:'Расклад создан для размышления и развлечения; он не предсказывает будущее.'
  };
}
